BenderTable *bender_core_env(BenderTable *replacements) {
    /* Memoize core env, ignoring replacements the second time around. */
    if (NULL != bender_vm.core_env) {
        return bender_vm.core_env;
    }

    BenderTable *dict = bender_core_lookup_table(replacements);

    /* Unmarshal bytecode */
    Bender marsh_out = bender_unmarshal(
                          bender_core_image,
                          bender_core_image_size,
                          0,
                          dict,
                          NULL);

    /* Memoize */
    bender_gcroot(marsh_out);
    BenderTable *env = bender_unwrap_table(marsh_out);
    bender_vm.core_env = env;

    /* Invert image dict manually here. We can't do this in boot.ben as it
     * breaks deterministic builds */
    Bender lidv, midv;
    lidv = midv = bender_wrap_nil();
    bender_resolve(env, bender_csymbol("load-image-dict"), &lidv);
    bender_resolve(env, bender_csymbol("make-image-dict"), &midv);

    /* Check that we actually got tables - if we are using a smaller corelib, may not exist */
    if (bender_checktype(lidv, BENDER_TABLE) && bender_checktype(midv, BENDER_TABLE)) {
        BenderTable *lid = bender_unwrap_table(lidv);
        BenderTable *mid = bender_unwrap_table(midv);
        for (int32_t i = 0; i < lid->capacity; i++) {
            const BenderKV *kv = lid->data + i;
            if (!bender_checktype(kv->key, BENDER_NIL)) {
                bender_table_put(mid, kv->value, kv->key);
            }
        }
    }

    return env;
}

#endif

BenderTable *bender_core_lookup_table(BenderTable *replacements) {
    BenderTable *dict = bender_table(512);
    bender_load_libs(dict);

    /* Add replacements */
    if (replacements != NULL) {
        for (int32_t i = 0; i < replacements->capacity; i++) {
            BenderKV kv = replacements->data[i];
            if (!bender_checktype(kv.key, BENDER_NIL)) {
                bender_table_put(dict, kv.key, kv.value);
                /* Add replacement functions to registry? */
            }
        }
    }

    return dict;
}
